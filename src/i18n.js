// Helpers de idioma para contenido con campos por idioma (es/pt/en o name_es/name_pt/name_en…).
// Siempre con fallback a español para que nada se rompa si falta una traducción.
export const pickLang = (obj, lang, prefix = '') =>
  (obj && (obj[prefix + lang] ?? obj[prefix + 'es'])) ?? ''
// Elige entre tres literales según el idioma, cayendo a español si falta.
export const tri = (lang, es, pt, en) => (lang === 'en' ? (en ?? es) : lang === 'pt' ? (pt ?? es) : es)

const LangContext = createContext(null)

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try { return localStorage.getItem('ml_lang') || 'es' } catch { return 'es' }
  })
  const setLang = useCallback((l) => {
    setLangState(l)
    try { localStorage.setItem('ml_lang', l) } catch { /* noop */ }
  }, [])
  const t = useCallback((key) => {
    return (LANG_DATA[lang] && LANG_DATA[lang][key]) ?? LANG_DATA.es[key] ?? key
  }, [lang])
  return createElement(LangContext.Provider, { value: { t, lang, setLang } }, children)
}

export function useLang() {
  const ctx = useContext(LangContext)
  if (!ctx) throw new Error('useLang debe usarse dentro de <LangProvider>')
  return ctx
}
